def find_program(*names):
    """First of ``names`` found next to this script or on PATH."""
    for name in names:
        candidates = [name]
        if sys.platform == "win32" and not name.lower().endswith(".exe"):
            candidates.append(name + ".exe")
        for candidate in candidates:
            local = APP_DIR / candidate
            if local.is_file():
                return str(local)
        path = shutil.which(name)
        if path:
            return path
    return None


def find_tool(setting):
    """Resolve a tool setting: an explicit path, a file beside this script,
    or a name on PATH (the same rules as the console transcriber)."""
    if not setting:
        return None
    value = os.path.expanduser(str(setting))
    if os.path.dirname(value) and Path(value).is_file():
        return str(Path(value))
    return find_program(value)


def find_ffmpeg():
    return find_tool(FFMPEG)


def find_ffprobe():
    tool = find_tool(FFPROBE)
    if tool:
        return tool
    ffmpeg = find_ffmpeg()
    if ffmpeg:
        # A full FFMPEG path usually has ffprobe right beside it.
        suffix = ".exe" if ffmpeg.lower().endswith(".exe") else ""
        sibling = Path(ffmpeg).with_name("ffprobe" + suffix)
        if sibling.is_file():
            return str(sibling)
    return None


def _duration_wave(path):
    with wave.open(str(path), "rb") as handle:
        frames = handle.getnframes()
        rate = handle.getframerate()
        if rate:
            return frames / float(rate)
    return None


def wave_duration(path):
    """Duration of a PCM WAV, or None (never raises)."""
    try:
        value = _duration_wave(path)
    except (OSError, EOFError, wave.Error, ValueError):
        return None
    return value if value and value > 0 else None


def _duration_ffprobe(path):
    tool = find_ffprobe()
    if not tool:
        return None
    result = subprocess.run(
        [tool, "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL, text=True, timeout=15,
        creationflags=hidden_process_flags(),
    )
    if result.returncode != 0:
        return None
    return float(result.stdout.strip())


FFMPEG_DURATION_RE = re.compile(r"Duration:\s*(\d+):(\d{2}):(\d{2}(?:\.\d+)?)")


def parse_ffmpeg_duration(output):
    """Seconds from the 'Duration: 00:01:02.50' line of ``ffmpeg -i``."""
    match = FFMPEG_DURATION_RE.search(str(output or ""))
    if not match:
        return None
    hours, minutes, seconds = match.groups()
    value = int(hours) * 3600 + int(minutes) * 60 + float(seconds)
    return value if value > 0 else None


def _duration_ffmpeg(path):
    """Duration from ``ffmpeg -i`` for setups that ship ffmpeg without ffprobe."""
    tool = find_ffmpeg()
    if not tool:
        return None
    result = subprocess.run(
        [tool, "-hide_banner", "-nostdin", "-i", str(path)],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE, text=True, errors="replace", timeout=15,
        creationflags=hidden_process_flags(),
    )
    # "At least one output file must be specified" makes the exit code 1.
    return parse_ffmpeg_duration(result.stderr)


def _duration_mutagen(path, kind=None):
    from mutagen import File as MutagenFile
    audio = MutagenFile(str(path))
    if audio is None and kind in ("mp4", "3gp"):
        # mutagen.File() does not pick its MP4 reader for .3gp/.3gpp names
        # (or files without an extension), although that reader handles them.
        from mutagen.mp4 import MP4
        audio = MP4(str(path))
    elif audio is None and kind == "adts":
        from mutagen.aac import AAC
        audio = AAC(str(path))
    if audio is not None and getattr(audio, "info", None) is not None:
        return float(audio.info.length)
    return None


def _duration_mci(path):
    """Windows MCI duration; avoids decoding or extra packages."""
    if sys.platform != "win32":
        return None
    import ctypes
    buffer = ctypes.create_unicode_buffer(64)
    mci = ctypes.windll.winmm.mciSendStringW
    path = Path(path)
    device = "waveaudio" if path.suffix.lower() == ".wav" else "mpegvideo"
    alias = "txtfromaudio_duration"
    try:
        if mci(f'open "{path}" type {device} alias {alias}', None, 0, 0):
            return None
        try:
            if mci(f"status {alias} length", buffer, 64, 0):
                return None
            milliseconds = float(buffer.value)
        finally:
            mci(f"close {alias}", None, 0, 0)
    except Exception:
        return None
    if milliseconds > 0:
        return milliseconds / 1000.0
    return None


def _duration_pygame(path):
    # pygame.mixer.Sound decodes the whole file into memory. Only use it for
    # small files; mutagen/ffprobe handle the big ones without decoding.
    try:
        if Path(path).stat().st_size > 12 * 1024 * 1024:
            return None
    except OSError:
        return None
    import pygame
    if not pygame.mixer.get_init():
        return None
    sound = pygame.mixer.Sound(str(path))
    return float(sound.get_length())


# No real recording needs more than this; a probe that implies it misread
# the file (e.g. a WAV header of compressed data read as PCM).
MAX_PLAUSIBLE_BITRATE = 100_000_000


def detect_duration(path, kind=None):
    """Best-effort duration in seconds, or None.

    In-process readers come first (wave, mutagen), then FFmpeg tools, then
    the platform/pygame fallbacks. mutagen is skipped where it reports
    nonsense: MPEG program streams (its MP3 reader invents a length) and
    compressed WAV (ADPCM/MP3 data measured as PCM: a few milliseconds).
    """
    if kind is None:
        kind = sniff_audio_kind(path)
    try:
        size = Path(path).stat().st_size
    except OSError:
        size = 0
    probes = [_duration_wave]
    if kind not in ("mpeg-ps", "wav-codec"):
        probes.append(lambda target: _duration_mutagen(target, kind))
    probes.extend([_duration_ffprobe, _duration_ffmpeg, _duration_mci])
    if kind is None or kind in PYGAME_NATIVE_KINDS:
        probes.append(_duration_pygame)
    for probe in probes:
        try:
            value = probe(path)
        except Exception:
            continue
        try:
            value = float(value) if value else 0.0
        except (TypeError, ValueError):
            continue
        if value <= 0:
            continue
        if size and size * 8 / value > MAX_PLAUSIBLE_BITRATE:
            continue
        return value
    return None


SILENCE_START_RE = re.compile(r"silence_start:\s*(-?\d+(?:\.\d+)?)")
SILENCE_END_RE = re.compile(r"silence_end:\s*(-?\d+(?:\.\d+)?)")


def parse_silences(output):
    """Return (start, end) silence spans from FFmpeg silencedetect output."""
    spans = []
    pending = None
    for line in str(output).splitlines():
        match = SILENCE_START_RE.search(line)
        if match:
            try:
                pending = max(0.0, float(match.group(1)))
            except ValueError:
                pending = None
            continue
        match = SILENCE_END_RE.search(line)
        if match:
            try:
                end = float(match.group(1))
            except ValueError:
                end = None
            if pending is not None and end is not None and end > pending:
                spans.append((pending, end))
            pending = None
    return spans


def speech_segments_from_silences(silences, duration,
                                  min_segment=SPEECH_MIN_SEGMENT_SECONDS,
                                  merge_gap=SPEECH_MERGE_GAP_SECONDS):
    """Complement of the silence spans inside [0, duration]."""
    try:
        duration = float(duration)
    except (TypeError, ValueError):
        return []
    if duration <= 0:
        return []
    segments = []
    cursor = 0.0
    for start, end in sorted(silences or ()):
        try:
            start = max(0.0, min(float(start), duration))
            end = max(0.0, min(float(end), duration))
        except (TypeError, ValueError):
            continue
        if start - cursor > min_segment:
            segments.append((cursor, start))
        cursor = max(cursor, end)
    if duration - cursor > min_segment:
        segments.append((cursor, duration))

    merged = []
    for start, end in segments:
        if merged and start - merged[-1][1] <= merge_gap:
            merged[-1] = (merged[-1][0], end)
        else:
            merged.append((start, end))
    return merged


def detect_speech_segments(path, duration=None, ffmpeg=None,
                           noise_db=SPEECH_NOISE_DB,
                           min_silence=SPEECH_MIN_SILENCE_SECONDS):
    """Speech runs found with ``ffmpeg silencedetect``; [] when unavailable.

    This only decodes audio (``-vn``) and writes no file, so it is cheap
    compared with transcription and needs no model.
    """
    if not SPEECH_ALIGNMENT:
        return []
    if ffmpeg is None:
        tool = find_ffmpeg()
    else:
        tool = ffmpeg
    if not tool:
        return []
    if duration is None:
        duration = detect_duration(path)
    try:
        duration = float(duration or 0.0)
    except (TypeError, ValueError):
        return []
    if duration <= 0:
        return []

    command = [
        tool, "-nostdin", "-hide_banner", "-i", str(path), "-vn",
        "-af", f"silencedetect=noise={noise_db}dB:d={min_silence}",
        "-f", "null", "-",
    ]
    try:
        result = subprocess.run(
            command,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
            errors="replace",
            check=False,
            creationflags=hidden_process_flags(),
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if result.returncode:
        return []
    return speech_segments_from_silences(parse_silences(result.stderr), duration)


