    def editor_text(self):
        return self.editor.get("1.0", "end-1c")

    def _set_editor_text(self, text):
        self._loading_text = True
        try:
            self._clear_marks_silent()
            self.editor.delete("1.0", "end")
            if text:
                self.editor.insert("1.0", text)
            self.editor.tag_remove("karaoke", "1.0", "end")
            self.editor.tag_remove("anchor", "1.0", "end")
            self.editor.edit_modified(False)
            self.editor.edit_reset()
            self._last_active_mark = None
        finally:
            self._loading_text = False
        self._set_dirty(False)
        self._marks_changed(save=False)

    def _set_dirty(self, value):
        self.dirty = bool(value)
        self._update_text_header()

    def _update_text_header(self):
        if self.current_audio is None:
            self.text_title.config(text="No text loaded")
            return
        name = self.text_path.name if self.text_path else "(unsaved text)"
        note = "" if (self.text_path and self.text_path.exists()) else "  (not created yet)"
        if self.dirty:
            note += "  *"
        self.text_title.config(text=name + note)

    def on_text_modified(self, _event=None):
        if not self.editor.edit_modified():
            return
        self.editor.edit_modified(False)
        if self._loading_text:
            return
        if not self.dirty:
            self.dirty = True
            self._update_text_header()
        if self.marks:
            # Keep the little anchor highlights attached to their words.
            self._refresh_anchor_tags()
            self._highlight_stale = True

    def confirm_discard(self):
        if not self.dirty:
            return True
        if self.text_path is None:
            return True
        answer = messagebox.askyesnocancel(
            "Unsaved text",
            f"{self.text_path.name} has unsaved changes.\n\nSave before continuing?",
        )
        if answer is None:
            return False
        if answer:
            return self.save_text()
        self._set_dirty(False)   # discard once, do not ask again for this file
        return True

    def _read_companion_text(self):
        """Text of the companion file, or None when it cannot be read."""
        try:
            text, encoding = read_text_with_encoding(self.text_path)
        except OSError as error:
            self.log(f"Could not read {self.text_path}: {error}")
            self.set_status(f"Could not read {self.text_path.name}; see the log.")
            return None
        if encoding != "utf-8":
            self.log(
                f"{self.text_path.name} is not UTF-8; read it as {encoding}. "
                "Saving writes UTF-8."
            )
        return text

    def reload_text(self):
        if self.current_audio is None or self.text_path is None:
            return
        if not self.confirm_discard():
            return
        if self.text_path.exists():
            text = self._read_companion_text()
            if text is None:
                return
            self._set_editor_text(text)
            self._load_sync_file()
            self.set_status(f"Reloaded {self.text_path.name}")
        else:
            self._set_editor_text("")
            self.set_status(f"{self.text_path.name} does not exist yet.")

    def save_text(self):
        if self.current_audio is None:
            messagebox.showinfo(
                "No audio selected",
                "Select an audio file first, so the text can be saved next to it.",
            )
            return False
        if self.text_path is None:
            return False
        try:
            write_text(self.text_path, self.editor_text())
        except OSError as error:
            messagebox.showerror("Could not save", f"{self.text_path}\n\n{error}")
            return False
        self._save_sync_file()
        self._set_dirty(False)
        self.refresh_audio_list()
        self.set_status(f"Saved {self.text_path.name}")
        return True

