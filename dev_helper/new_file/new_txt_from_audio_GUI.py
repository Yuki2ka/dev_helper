    def toggle_transcriber(self):
        if self.transcriber_proc is not None:
            self.cancel_transcriber()
            return

        if self.current_audio is None and not self.run_all_var.get():
            messagebox.showinfo("No audio selected", "Select an audio file first.")
            return

        if self.dirty:
            answer = messagebox.askyesnocancel(
                "Unsaved text",
                "Save the current text before running the transcriber?",
            )
            if answer is None:
                return
            if answer and not self.save_text():
                return

        script = Path(self.transcriber_script)
        if not script.exists():
            if not messagebox.askyesno(
                "Transcriber not found",
                f"Expected:\n{script}\n\nThe GUI can run any script that writes "
                "<audio name>.txt next to the audio file.\n\nLocate it now?",
            ):
                return
            chosen = filedialog.askopenfilename(
                title="Locate the transcriber script",
                initialdir=str(APP_DIR),
                filetypes=[("Python script", "*.py"), ("All files", "*.*")],
            )
            if not chosen:
                return
            self.transcriber_script = Path(chosen)
            script = self.transcriber_script

        if self.run_all_var.get():
            if self.folder is None:
                messagebox.showinfo("No folder", "Open an audio folder first.")
                return
            targets = [
                path for path in scan_audio(
                    self.folder, recursive=self._recursive_enabled()
                )
                if not companion_path(path, TEXT_SUFFIX).exists()
            ]
            if not targets:
                messagebox.showinfo(
                    "Nothing to do",
                    "Every audio file in this folder already has a text file.",
                )
                return
        else:
            targets = [self.current_audio]

        self.run_queue = list(targets)
        self.run_total = len(self.run_queue)
        self.run_done = 0
        self.run_failures = 0
        self.run_button.config(text="Stop transcriber")
        self.run_status.config(text=f"Starting 0/{self.run_total}...")
        self.log("")
        self.log(f"Transcriber: {script}")
        self._start_next_transcription()

    def _start_next_transcription(self):
        if not self.run_queue:
            self._finish_run()
            return
        audio = self.run_queue.pop(0)
        script = Path(self.transcriber_script)

        try:
            command = self._transcriber_command(script, audio)
        except Exception as error:
            messagebox.showerror("Could not build command", str(error))
            self._finish_run()
            return

        self.log("$ " + " ".join(f'"{part}"' if " " in part else part
                                 for part in command))

        try:
            # Its own process tree, so Stop also ends the ffmpeg/ASR
            # processes the transcriber starts (see stop_process_tree).
            process = subprocess.Popen(
                command,
                cwd=str(script.parent),
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                bufsize=1,
                env=self._child_environment(),
                **tree_popen_options(),
            )
        except OSError as error:
            # The same error would repeat for every queued file.
            self.log(f"Could not run transcriber: {error}")
            messagebox.showerror("Could not run transcriber", str(error))
            self.run_failures += 1 + len(self.run_queue)
            self.run_queue = []
            self._finish_run()
            return

        self.transcriber_proc = process
        self.running_audio = audio
        self.run_status.config(
            text=f"Running {self.run_done + 1}/{self.run_total}: {audio.name}"
        )
        threading.Thread(
            target=self._read_transcriber,
            args=(process, audio),
            daemon=True,
        ).start()

    def _child_environment(self):
        env = dict(os.environ)
        env["PYTHONIOENCODING"] = "utf-8"
        env["PYTHONUNBUFFERED"] = "1"
        return env

    def _transcriber_command(self, script, audio):
        audio = Path(audio)
        arguments = []
        for template in TRANSCRIBER_ARGS:
            arguments.append(
                str(template).format(
                    audio=str(audio),
                    folder=str(audio.parent),
                    out=str(companion_path(audio, TEXT_SUFFIX)),
                )
            )
        return [console_python(), str(script)] + arguments

    def _read_transcriber(self, process, audio):
        try:
            if process.stdout is not None:
                for line in process.stdout:
                    self.worker_queue.put(("log", line.rstrip("\r\n")))
        finally:
            code = process.wait()
            self.worker_queue.put(("proc_done", (process, audio, code)))

    def _drain_worker_queue(self):
        while True:
            try:
                kind, payload = self.worker_queue.get_nowait()
            except queue.Empty:
                return
            if kind == "log":
                self.log(payload)
            elif kind == "proc_done":
                self._on_transcriber_done(*payload)
            elif kind == "install_done":
                self._on_install_done(*payload)
            elif kind == "align_done":
                self._on_align_done(*payload)
            elif kind == "prepare_progress":
                self._on_prepare_progress(*payload)
            elif kind == "prepare_done":
                self._on_prepare_done(*payload)

    def _on_transcriber_done(self, process, audio, code):
        if process is not self.transcriber_proc:
            return
        self.transcriber_proc = None
        self.running_audio = None
        self.run_done += 1
        if code != 0:
            self.run_failures += 1
        self.log(f"[exit {code}] {audio.name}")

        self.refresh_audio_list()
        if self.current_audio == audio:
            self._reload_after_transcription(audio)

        if self.run_queue:
            self._start_next_transcription()
        else:
            self._finish_run()

    def _reload_after_transcription(self, audio):
        if self.dirty:
            self.log("Text has unsaved changes; not reloaded automatically.")
            return
        text_file = companion_path(audio, TEXT_SUFFIX)
        if text_file.exists():
            self.text_path = text_file
            text = self._read_companion_text()
            if text is None:
                return
            self._set_editor_text(text)
            self._set_dirty(False)
            loaded = self._load_sync_file()
            if not loaded:
                self._auto_import_timings()
            self._auto_align(audio)
            self.set_status(f"Loaded {text_file.name}")
        else:
            self.log(
                f"No {text_file.name} was created. Check that the transcriber "
                "writes <audio name>.txt."
            )

    def _finish_run(self):
        self.transcriber_proc = None
        self.running_audio = None
        self.run_button.config(text="Run new_txt_from_audio.py")
        if self.run_total:
            summary = f"Finished {self.run_done}/{self.run_total}"
            if self.run_failures:
                summary += f", {self.run_failures} failed"
            self.run_status.config(text=summary)
            self.log(summary + ".")
            self.set_status(summary + ".")
        else:
            self.run_status.config(text="")
        self.refresh_audio_list()

    def cancel_transcriber(self):
        self.run_queue.clear()
        process = self.transcriber_proc
        if process is None:
            return
        self.log("Stopping transcriber...")
        stop_process_tree(process)

